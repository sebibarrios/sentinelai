"use client";

import { Sparkles } from "lucide-react";

import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/table";
import { ApiError } from "@/lib/api";
import type { AiAnalysis } from "@/lib/types";
import { formatDateTime } from "@/lib/utils";

/**
 * Container for anything a model wrote. It is visually distinct from verified data
 * (dashed periwinkle border, explicit label) and always names the model, prompt
 * version, and who requested it, so an analyst can judge how much to trust it.
 */
export function AiPanel({
  title,
  description,
  analysis,
  aiEnabled,
  canRequest,
  generating,
  error,
  onGenerate,
  generateLabel,
  children,
}: {
  title: string;
  description: string;
  analysis: AiAnalysis<unknown> | null | undefined;
  aiEnabled: boolean | undefined;
  canRequest: boolean;
  generating: boolean;
  error: unknown;
  onGenerate: () => void;
  generateLabel: string;
  children?: React.ReactNode;
}) {
  return (
    <section
      aria-labelledby="ai-panel-title"
      className="rounded-lg border border-dashed border-primary/50 bg-primary/[0.04] p-5"
    >
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 id="ai-panel-title" className="flex items-center gap-2 font-medium">
            <Sparkles className="size-4 text-primary" aria-hidden />
            {title}
          </h2>
          <p className="mt-1 text-sm text-muted-foreground">
            AI-generated suggestions. Check them against the verified evidence before acting.
          </p>
        </div>
        {canRequest && aiEnabled && (
          <Button size="sm" variant="outline" onClick={onGenerate} disabled={generating}>
            <Sparkles />
            {generating ? "Analyzing…" : analysis ? "Regenerate" : generateLabel}
          </Button>
        )}
      </div>

      {error ? (
        <p role="alert" className="mt-4 text-sm text-sev-critical">
          {error instanceof ApiError ? error.displayMessage : "The AI request failed."}
        </p>
      ) : null}

      <div className="mt-4">
        {generating && !analysis ? (
          <div className="flex flex-col gap-2" aria-busy>
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-5/6" />
            <Skeleton className="h-4 w-2/3" />
          </div>
        ) : analysis ? (
          <>
            {children}
            <p className="mt-5 border-t border-dashed border-primary/30 pt-3 text-xs text-muted-foreground">
              Generated by {analysis.model} (prompt {analysis.prompt_version}) for{" "}
              {analysis.requested_by.full_name}, {formatDateTime(analysis.created_at)}.
            </p>
          </>
        ) : aiEnabled === false ? (
          <p className="text-sm text-muted-foreground">
            AI analysis isn&apos;t configured on this server. Set OPENAI_API_KEY on the backend to
            enable it.
          </p>
        ) : (
          <p className="text-sm text-muted-foreground">
            {canRequest ? description : "No analysis yet. Analysts can request one."}
          </p>
        )}
      </div>
    </section>
  );
}

export function AiList({ title, items }: { title: string; items: string[] }) {
  if (!items.length) return null;
  return (
    <div>
      <h3 className="mb-1.5 text-sm font-medium text-muted-foreground">{title}</h3>
      <ul className="flex list-disc flex-col gap-1 pl-5">
        {items.map((item, i) => (
          <li key={i}>{item}</li>
        ))}
      </ul>
    </div>
  );
}
