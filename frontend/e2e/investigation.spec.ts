import { expect, loginAndWait, rows, test } from "./fixtures";

test("alert -> AI explanation -> incident -> AI report -> notes and history", async ({ page }) => {
  await loginAndWait(page, "analyst");

  // 1. Open the brute-force alert: verified facts and the exact evidence rows.
  await page.goto("/alerts?rule_id=AUTH-001");
  await page.getByRole("link", { name: /Brute force: 12 failed logins/ }).click();
  await expect(page.getByRole("heading", { name: "Verified finding" })).toBeVisible();
  await expect(page.getByRole("heading", { name: /Evidence/ })).toContainText("(12)");
  const evidence = page.locator("section", { has: page.getByRole("heading", { name: /Evidence/ }) });
  await expect(evidence.locator("tbody tr:visible")).toHaveCount(12);

  // 2. AI explanation is labeled as AI and names what produced it.
  const ai = page.locator("section", { has: page.getByRole("heading", { name: "AI analyst" }) });
  await expect(ai).toContainText("AI-generated suggestions");
  await ai.getByRole("button", { name: "Explain this alert" }).click();
  await expect(ai).toContainText("[Offline fixture]");
  await expect(ai).toContainText("203.0.113.45"); // built from this alert's data
  await expect(ai).toContainText("Generated by offline-fixture");

  // 3. Promote to an incident, which records the verified facts in its description.
  await page.getByRole("button", { name: "Promote to incident" }).click();
  await expect(page).toHaveURL(/\/incidents\/[0-9a-f-]{36}$/);
  await expect(page.getByText("Verified facts from detection:")).toBeVisible();
  await expect(page.getByRole("heading", { name: /Linked alerts/ })).toContainText("(1)");

  // 4. The AI report drops an indicator that isn't in the incident's data.
  await page.getByRole("button", { name: "Draft report" }).click();
  await expect(page.getByText("Executive summary")).toBeVisible();
  await expect(page.getByText("1 indicator was removed because it doesn't appear")).toBeVisible();
  await expect(page.getByText("192.0.2.254")).toHaveCount(0);

  // 5. Work the incident; every change lands in the history.
  await page.getByRole("button", { name: "Edit" }).click();
  await page.getByLabel("Title").fill("Brute force on admin account (confirmed)");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(
    "Brute force on admin account (confirmed)",
  );
  await page.getByRole("combobox", { name: "Status", exact: true }).click();
  await page.getByRole("option", { name: "Contained" }).click();
  await expect(page.getByText("Status set to contained")).toBeVisible();
  await page.getByLabel("Add a note").fill("Blocked 203.0.113.45 at the edge firewall.");
  await page.getByRole("button", { name: "Add note" }).click();
  await expect(page.getByText("Blocked 203.0.113.45 at the edge firewall.")).toBeVisible();

  const history = page.locator("section", { has: page.getByRole("heading", { name: "History" }) });
  for (const entry of [
    "linked an alert",
    "changed title from",
    "changed status from open to contained",
    "added a note",
  ]) {
    await expect(history).toContainText(entry);
  }
});

test("creating an incident by hand", async ({ page }) => {
  await loginAndWait(page, "analyst");
  await page.goto("/incidents");
  await page.getByRole("button", { name: "New incident" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Title").fill("Suspicious mailbox forwarding rule");
  await dialog.getByLabel("Description").fill("Rule forwards finance mail externally.");
  await dialog.getByRole("button", { name: "Create incident" }).click();
  await expect(page).toHaveURL(/\/incidents\/[0-9a-f-]{36}$/);
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(
    "Suspicious mailbox forwarding rule",
  );

  await page.goto("/incidents");
  await page.getByLabel("Search incidents").fill("mailbox forwarding");
  await expect(rows(page)).toHaveCount(1);
});
